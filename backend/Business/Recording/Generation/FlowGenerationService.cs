        public async Task<ResultDto<FlowGenerationResultDto>> ImportPlainDraftAsync(
            int flowId,
            RecordingResultDto recording,
            ReviewedRecordingDto reviewed,
            Func<int, RecordingScreenDto?> screenAt,
            CancellationToken ct = default)
        {
            FlowScriptSchema flow = await _exporter.LoadAsync(flowId, ct);
            if (flow.Flow.IsQaTest)
                return ResultDto<FlowGenerationResultDto>.Failure("A QA test is generated by the model only. Start Ollama with a model chosen in Settings, then generate it.");

            FlowGenerationResultDto result = new FlowGenerationResultDto();
            result.Import = await ImportPlainAsync(flow, recording, reviewed, screenAt, ct);

            await ReadSavedAsync(result, ct);
            return ResultDto<FlowGenerationResultDto>.Success(result);
        }

        public async Task<ResultDto<FlowScriptImportResultDto>> InsertPlainDraftAsync(
            RecordingDraftPositionDto position,
            RecordingResultDto recording,
            ReviewedRecordingDto reviewed,
            Func<int, RecordingScreenDto?> screenAt,
            CancellationToken ct = default)
        {
            FlowScriptSchema flow = await _exporter.LoadAsync(position.FlowId, ct);

            FlowStep? under = null;
            if (position.ParentFlowStepId != null)
            {
                under = flow.Steps.FirstOrDefault(x => x.Id == position.ParentFlowStepId);
                if (under == null)
                    return ResultDto<FlowScriptImportResultDto>.Failure("The step the recording goes under is no longer in the flow.");
            }

            HashSet<FlowStep> stepsBefore = flow.Steps.ToHashSet();

            RecordingDraft draft = _draftBuilder.Build(flow, recording, reviewed, screenAt, under, position.Index);
            FlowScriptSchema schema = draft.Lay();
            await _dataService.DiscordBot.NameAsync(schema, ct);

            string script = _printer.Write(schema);
            FlowScriptSchema read = _scanner.Read(script);
            if (!read.IsValid)
            {
                FlowScriptImportResultDto refused = FlowScriptImporter.Failed(read.Diagnostics);
                return ResultDto<FlowScriptImportResultDto>.Success(refused);
            }

            List<FlowStep> steps = schema.Steps.Where(x => !stepsBefore.Contains(x)).ToList();
            List<FlowCsvColumn> inputs = draft.AddedInputs.ToList();

            // The tree insert hangs them at the position by its ids, as it renumbers the steps there.
            foreach (FlowStep step in steps.Where(x => x.ParentFlowStep == under))
                step.ParentFlowStep = null;

            ResultDto<int> saved = await _dataService.FlowStep.CreateTreeAsync(position.FlowId, position.ParentFlowStepId, position.Index, steps, inputs, ct);
            if (!saved.IsSuccess)
                return ResultDto<FlowScriptImportResultDto>.Failure(saved.ErrorMessage ?? "The recording could not be written into the flow.");

            FlowScriptImportResultDto inserted = new FlowScriptImportResultDto
            {
                IsSuccess = true,
                FlowId = saved.Data,
                FlowName = flow.Flow.Name,
                StepCount = steps.Count,
                TemplateCount = steps.SelectMany(x => x.FlowStepTemplates).Select(x => x.FlowTemplate).Distinct().Count(),
            };

            return ResultDto<FlowScriptImportResultDto>.Success(inserted);
        }

        public async Task<FlowGenerationResultDto> ImportModelDraftAsync(
            int flowId,
            RecordingResultDto recording,
            ReviewedRecordingDto reviewed,
            Func<int, RecordingScreenDto?> screenAt,
            Action<FlowGenerationProgressDto>? onProgress,
            Func<CancellationToken, Task> waitToSend,
            CancellationToken ct = default)
        {
            bool isReadTextSent = await _providerService.CanSendScreenDataAsync(ct);
            string model = await _providerService.GetModelAsync(ct);

            FlowGenerationProgressDto looking = new FlowGenerationProgressDto
            {
                State = FlowGenerationStateEnum.GENERATING,
                Stage = FlowGenerationStageEnum.LOOKING_AT_SCREENS,
                Model = model,
                IsReadTextSent = isReadTextSent,
                AttemptCount = RecordingWordsService.ATTEMPT_COUNT,
            };
            onProgress?.Invoke(looking);

            // Withheld, the steps get placeholder names, and the model names them from the
            // description - and what the local model would say of the screen is withheld as well,
            // so it is not asked.
            RecordingResultDto sent;
            if (isReadTextSent)
            {
                IReadOnlyList<ScreenDescriptionDto> seen = await _screenDescriber.DescribeAsync(recording, reviewed, screenAt, (done, total) =>
                {
                    looking = Looking(looking, done, total);
                    onProgress?.Invoke(looking);
                }, ct);

                sent = WithDescriptions(recording, seen);
            }
            else
            {
                sent = WithoutReadText(recording);
            }

            FlowGenerationProgressDto writing = Next(looking, FlowGenerationStageEnum.WRITING_DRAFT, 0, []);
            onProgress?.Invoke(writing);

            FlowScriptSchema flow = await _exporter.LoadAsync(flowId, ct);
            bool isQaTest = flow.Flow.IsQaTest;
            FlowArea? mainArea = flow.Areas.FirstOrDefault(x => x.IsMain);
            string example = FlowExamples.WordsOf(_exampleIndex.DocumentFor(flow.Flow, mainArea));

            RecordingDraft draft = _draftBuilder.Build(flow, sent, reviewed, screenAt, null, null);
            FlowScriptSchema schema = draft.Lay();
            await _dataService.DiscordBot.NameAsync(schema, ct);

            // What the Check page marks the model's words against.
            string plainScript = _printer.Write(schema);
            FlowScriptSchema plain = _scanner.Read(plainScript);
            Dictionary<string, byte[]> templates = TemplatesOf(schema);

            RecordingOutline outline = RecordingOutline.Of(draft, sent);
            string request = _wordsService.RequestOf(outline, example);
            List<int> requestScreenLines = ScreenTextLines.Of(request, sent, reviewed, isReadTextSent);

            FlowGenerationProgressDto drafted = Next(writing, FlowGenerationStageEnum.WRITING_DRAFT, 0, []);
            drafted.ScriptLength = request.Length;

            // Text read off the screen leaves this machine only once the tester has read it.
            if (requestScreenLines.Count > 0 && await _providerService.IsCloudModelInUseAsync(ct))
            {
                FlowGenerationProgressDto waiting = Next(drafted, FlowGenerationStageEnum.WAITING_TO_SEND, 0, []);
                waiting.Request = request;
                waiting.RequestScreenLines = requestScreenLines;
                onProgress?.Invoke(waiting);

                await waitToSend(ct);
            }

            Action<int> onAttempt = attempt => onProgress?.Invoke(Next(drafted, FlowGenerationStageEnum.ASKING_MODEL, attempt, []));
            RecordingWordsResult named = await _wordsService.NameAsync(outline, request, isReadTextSent, onAttempt, ct);

            FlowGenerationResultDto result = new FlowGenerationResultDto
            {
                Attempts = named.Attempts,
                Request = named.Request,
                RequestScreenLines = requestScreenLines,
            };

            if (named.Words == null)
            {
                onProgress?.Invoke(Next(drafted, FlowGenerationStageEnum.SAVING, named.Attempts, []));

                // Built again from the recording itself, so its names have the text read under each click.
                result.Reason = named.ErrorMessage ?? "The model gave no words.";
                FlowScriptSchema reloaded = await _exporter.LoadAsync(flowId, ct);
                result.Import = await ImportPlainAsync(reloaded, recording, reviewed, screenAt, ct);

                await ReadSavedAsync(result, ct);
                return result;
            }

            AppliedWords applied = new AppliedWords();
            RecordingWordsApplier.ApplyNames(draft, outline, named.Words, applied);

            if (isQaTest)
            {
                RecordingOutline renamed = RecordingOutline.Of(draft, sent);
                RecordingWordsResult proposed = await _wordsService.ProposeTestAsync(renamed, isReadTextSent, onAttempt, ct);
                if (proposed.Words != null)
                    RecordingWordsApplier.ApplyTest(draft, renamed, proposed.Words, sent, applied);
                else
                    applied.NotTaken.Add($"No stages or checks were proposed: {proposed.ErrorMessage}");

                RecordingWordsApplier.MakeTest(draft, flow.Flow.Name);
            }

            onProgress?.Invoke(Next(drafted, FlowGenerationStageEnum.SAVING, named.Attempts, []));

            result.IsModelDraft = true;
            result.Notes = applied.Notes;
            result.Questions = applied.Questions;
            result.NotTaken = applied.NotTaken;
            result.Draft = plainScript;
            result.Import = await _importer.ImportTextAsync(_printer.Write(draft.Lay()), templates, ct);

            FlowScriptSchema? saved = await ReadSavedAsync(result, ct);
            if (saved != null)
                result.ProposedChecks = ProposedChecks.ToDtos(ProposedChecks.Find(plain, saved, []), result.Script, recording.ScreenLines);

            return result;
        }

        public async Task<FlowGenerationResultDto> ReviseAsync(
            int flowId,
            string changes,
            IReadOnlyCollection<string> undecided,
            IReadOnlyList<string> screenLines,
            Action<FlowGenerationProgressDto>? onProgress,
            CancellationToken ct = default)
        {
            string model = await _providerService.GetModelAsync(ct);

            // The script is the flow as the tester has read it, so it goes as it is.
            FlowGenerationProgressDto reading = new FlowGenerationProgressDto
            {
                State = FlowGenerationStateEnum.GENERATING,
                Stage = FlowGenerationStageEnum.WRITING_DRAFT,
                Model = model,
                IsReadTextSent = true,
                AttemptCount = ScriptRevisionService.ATTEMPT_COUNT,
            };
            onProgress?.Invoke(reading);

            string script = await _exporter.RenderAsync(flowId, ct);
            FlowScriptSchema flow = await _exporter.LoadAsync(flowId, ct);
            Dictionary<string, byte[]> templates = TemplatesOf(flow);

            FlowGenerationProgressDto read = Next(reading, FlowGenerationStageEnum.WRITING_DRAFT, 0, []);
            read.ScriptLength = script.Length;

            string example = _exampleIndex.DocumentFor(flow.Flow, flow.Areas.FirstOrDefault(x => x.IsMain));
            string instruction = $"{AiPromptHelper.ReviseOnRequest}\n\nWhat the tester asks for:\n\n{changes.Trim()}";
            instruction += $"\n\n{FlowExamples.ForRequest(example)}";

            ScriptRevisionResult revision = await _revisionService.ReviseAsync(script, instruction, null, (attempt, refused) =>
            {
                FlowGenerationProgressDto asking = Next(read, FlowGenerationStageEnum.ASKING_MODEL, attempt, refused);
                onProgress?.Invoke(asking);
            }, ct);

            FlowGenerationResultDto result = new FlowGenerationResultDto
            {
                Notes = revision.Notes,
                Attempts = revision.Attempts,
                Request = revision.Request,
                Draft = script,
            };

            if (revision.Script == null)
            {
                result.Reason = revision.ErrorMessage ?? $"No answer from the model read cleanly in {revision.Attempts} attempts, so the flow is as it was.";
                result.Refused = FlowScriptImporter.ToDtos(revision.Refused, DiagnosticSeverityEnum.ERROR);
                return result;
            }

            FlowGenerationProgressDto saving = Next(read, FlowGenerationStageEnum.SAVING, revision.Attempts, []);
            onProgress?.Invoke(saving);

            result.IsModelDraft = true;
            result.Import = await _importer.ImportTextAsync(revision.Script, templates, ct);

            FlowScriptSchema? saved = await ReadSavedAsync(result, ct);
            if (saved != null)
                result.ProposedChecks = ProposedChecks.ToDtos(ProposedChecks.Find(flow, saved, undecided), result.Script, screenLines);

            return result;
        }

        public async Task<ResultDto<FlowGenerationResultDto>> DropCheckAsync(
            ProposedCheckDropDto drop,
            IReadOnlyList<string> screenLines,
            CancellationToken ct = default)
        {
            FlowScriptSchema flow = await _exporter.LoadAsync(drop.FlowId, ct);
            Dictionary<string, byte[]> templates = TemplatesOf(flow);

            string? refused = ProposedChecks.Drop(flow, drop.Name);
            if (refused != null)
                return ResultDto<FlowGenerationResultDto>.Failure(refused);

            FlowGenerationResultDto result = new FlowGenerationResultDto { IsModelDraft = true };
            result.Import = await _importer.ImportTextAsync(_printer.Write(flow), templates, ct);
            if (!result.Import.IsSuccess)
                return ResultDto<FlowGenerationResultDto>.Failure($"The flow could not be saved without \"{drop.Name}\", so it is as it was.");

            FlowScriptSchema? saved = await ReadSavedAsync(result, ct);
            if (saved != null)
            {
                List<FlowStep> undecided = drop.Undecided
                    .Where(x => !string.Equals(x, drop.Name, StringComparison.OrdinalIgnoreCase))
                    .Select(x => ProposedChecks.Named(saved, x))
                    .OfType<FlowStep>()
                    .ToList();

                result.ProposedChecks = ProposedChecks.ToDtos(undecided, result.Script, screenLines);
            }

            return ResultDto<FlowGenerationResultDto>.Success(result);
        }


        // ================================================================
        // Private methods
        // ================================================================

        private async Task<FlowScriptImportResultDto> ImportPlainAsync(
            FlowScriptSchema flow,
            RecordingResultDto recording,
            ReviewedRecordingDto reviewed,
            Func<int, RecordingScreenDto?> screenAt,
            CancellationToken ct)
        {
            RecordingDraft draft = _draftBuilder.Build(flow, recording, reviewed, screenAt, null, null);
            FlowScriptSchema schema = draft.Lay();

            // The import finds each Notify's bot by the name its line gives.
            await _dataService.DiscordBot.NameAsync(schema, ct);

            string script = _printer.Write(schema);
            Dictionary<string, byte[]> templates = TemplatesOf(schema);

            return await _importer.ImportTextAsync(script, templates, ct);
        }

        // The flow as saved, read back from the database rather than taken from what was sent to it.
        // Null when nothing was saved.
        private async Task<FlowScriptSchema?> ReadSavedAsync(FlowGenerationResultDto result, CancellationToken ct)
        {
            if (!result.Import.IsSuccess)
                return null;

            result.Script = await _exporter.RenderAsync(result.Import.FlowId, ct);
            FlowScriptSchema saved = _scanner.Read(result.Script);

            result.StepCount = saved.Steps.Count(x => x.FlowStepType != FlowStepTypeEnum.SUCCESS && x.FlowStepType != FlowStepTypeEnum.FAILURE);
            result.InputCount = saved.Inputs.Count;
            result.TemplateCount = saved.Steps
                .SelectMany(x => x.FlowStepTemplates)
                .Select(x => x.FlowTemplate.Name)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .Count();

            return saved;
        }

        // By name, as an import reads them: the ones cut from the recording and the ones the flow had.
        private static Dictionary<string, byte[]> TemplatesOf(FlowScriptSchema draft)
        {
            Dictionary<string, byte[]> templates = new Dictionary<string, byte[]>(StringComparer.OrdinalIgnoreCase);

            foreach (FlowTemplate template in draft.Steps.SelectMany(x => x.FlowStepTemplates).Select(x => x.FlowTemplate))
            {
                if (template.TemplateImage != null)
                    templates[template.Name] = template.TemplateImage;
            }

            return templates;
        }

        // The same recording with nothing read off the screen: no text under a click, no lines, no
        // window title, no name Windows had. How much changed, that a title changed, which page a
        // press was on, and what kind of element was pressed in what state are not screen text, and stay.
        private static RecordingResultDto WithoutReadText(RecordingResultDto recording)
        {
            List<ClickedElementDto> elements = recording.ClickedElements
                .Select(x => new ClickedElementDto
                {
                    ActionIndex = x.ActionIndex,
                    X = x.X,
                    Y = x.Y,
                    Width = x.Width,
                    Height = x.Height,
                    FoundBy = x.FoundBy,
                    Note = x.Note,
                    Image = x.Image,
                })
                .ToList();

            List<ScreenChangeDto> changes = recording.ScreenChanges
                .Select(x => new ScreenChangeDto
                {
                    ActionIndex = x.ActionIndex,
                    NextActionIndex = x.NextActionIndex,
                    ChangedShare = x.ChangedShare,
                    IsNewScreen = x.IsNewScreen,
                    IsNewTitle = x.IsNewTitle,
                })
                .ToList();

            List<PressedElementDto> pressed = recording.PressedElements
                .Select(x => new PressedElementDto
                {
                    ActionIndex = x.ActionIndex,
                    Role = x.Role,
                    IsEnabled = x.IsEnabled,
                    IsChecked = x.IsChecked,
                    IsPassword = x.IsPassword,
                })
                .ToList();

            return new RecordingResultDto
            {
                Actions = recording.Actions,
                ClickedElements = elements,
                ClickGroups = recording.ClickGroups,
                ScreenChanges = changes,
                ScreenPages = recording.ScreenPages,
                PressedElements = pressed,
            };
        }

        // The same recording with what the local model saw at it.
        private static RecordingResultDto WithDescriptions(RecordingResultDto recording, IReadOnlyList<ScreenDescriptionDto> seen)
        {
            return new RecordingResultDto
            {
                Actions = recording.Actions,
                ClickedElements = recording.ClickedElements,
                ClickGroups = recording.ClickGroups,
                ScreenChanges = recording.ScreenChanges,
                ScreenPages = recording.ScreenPages,
                ScreenLines = recording.ScreenLines,
                PressedElements = recording.PressedElements,
                ScreenDescriptions = seen.ToList(),
            };
        }

        // A new one each time, since the last may still be on its way to the page.
        private static FlowGenerationProgressDto Next(FlowGenerationProgressDto last, FlowGenerationStageEnum stage, int attempt, IReadOnlyList<Diagnostic> refused)
        {
            return new FlowGenerationProgressDto
            {
                State = last.State,
                Stage = stage,
                Model = last.Model,
                IsReadTextSent = last.IsReadTextSent,
                ScriptLength = last.ScriptLength,
                LookedAt = last.LookedAt,
                ToLookAt = last.ToLookAt,
                Attempt = attempt,
                AttemptCount = last.AttemptCount,
                Refused = FlowScriptImporter.ToDtos(refused, DiagnosticSeverityEnum.ERROR),
            };
        }

        private static FlowGenerationProgressDto Looking(FlowGenerationProgressDto last, int done, int total)
        {
            FlowGenerationProgressDto looking = Next(last, FlowGenerationStageEnum.LOOKING_AT_SCREENS, 0, []);
            looking.LookedAt = done;
            looking.ToLookAt = total;

            return looking;
        }
    }
